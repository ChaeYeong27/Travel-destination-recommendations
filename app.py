def progress_html(step):
    pct = (step - 1) / len(QUESTIONS) * 100
    left = min(max(pct, 3), 97)
    plane = (f'<img class="pl" src="{PLANE_3D}" style="left:{left:.1f}%" alt="">' if image_ok(PLANE_3D)
             else f'<span class="pl" style="left:{left:.1f}%">✈️</span>')
    return (f'<div class="progress-wrap"><div class="route"><div class="line"></div>'
            f'<div class="done" style="width:{pct:.1f}%"></div><div class="end">🏝️</div>{plane}</div>'
            f'<div class="progress-txt"><span><b>{step}</b> / {len(QUESTIONS)} 질문</span>'
            f'<span>목적지까지 {len(QUESTIONS) - step + 1}개 남았어요</span></div></div>')


