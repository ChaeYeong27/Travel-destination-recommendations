def page_question(step):
    q = QUESTIONS[step - 1]
    pic = emoji_img(Q_IMAGE[step - 1], Q_FALLBACK[step - 1], "ill")
    st.markdown(
        f'<div class="q-head"><span class="q-num">Q{step}.</span><span class="q-text">{q["q"]}</span></div>'
        f'<div class="q-pic"><span class="tag">{q["tag"]}</span>{pic}</div>', unsafe_allow_html=True)
    opts = q["opts"]
    with st.container(key=f"opt_{step}"):
        for row in range(0, len(opts), 2):
            cols = st.columns(2, gap="medium")
            for j, col in enumerate(cols):
                i = row + j + 1
                if i <= len(opts):
                    emo, text = opts[i - 1]
                    with col:
                        st.button(f"{emo}  {text}", key=f"q{step}_{i}", on_click=choose, args=(i,))
    with st.container(key=f"back_{step}"):
        st.button("← 이전으로 돌아가기" if step > 1 else "← 처음으로", on_click=go, args=(step - 1,))
    st.markdown(progress_html(step), unsafe_allow_html=True)


def page_result():
    a = st.session_state.answers
    top = recommend(a, top_n=3)
    passenger = (st.session_state.passenger or "TRAVELER").strip()[:12]
    st.markdown(f'<div class="res-title"><span class="chip">탑승권 발권 완료 🎉</span>'
                f'<h2>{passenger}님의 인생 여행지는<br><span>{top[0]["name"]}</span>입니다!</h2></div>',
                unsafe_allow_html=True)
    with st.spinner("탑승권을 발권하고 있어요..."):
        st.markdown(pass_html(top[0], a, passenger, 1), unsafe_allow_html=True)
    st.markdown(alt_html(top[1:]), unsafe_allow_html=True)
    st.markdown(answers_html(a), unsafe_allow_html=True)
    st.write("")
    with st.container(key="main_restart"):
        st.button("다시 여행지 찾기  ↺", on_click=restart)


def password_gate():
    """Streamlit Secrets에 password가 있으면 입장 전에 비밀번호를 묻는다 (없으면 바로 통과)"""
    try:
        password = st.secrets["password"]
    except Exception:
        return True
    if st.session_state.get("pw_ok"):
        return True

    def check():
        typed = st.session_state.get("pw_input", "")
        st.session_state.pw_ok = hmac.compare_digest(typed, str(password))
        st.session_state.pw_tried = True

    lock = (f'<img class="globe" src="{EMOJI_3D.format("1f512")}" alt="">' if image_ok(EMOJI_3D.format("1f512"))
            else '<span class="emo">🔒</span>')
    st.markdown(f'<div class="hero">{lock}<br><span class="chip">BOARDING CHECK</span>'
                '<h1>탑승객 <span>확인</span></h1><p>비밀번호를 입력하고 탑승을 시작하세요.</p></div>',
                unsafe_allow_html=True)
    st.text_input("비밀번호", type="password", key="pw_input", on_change=check,
                  placeholder="비밀번호", label_visibility="collapsed")
    with st.container(key="main_pw"):
        st.button("입장하기  ✈", on_click=check)
    if st.session_state.get("pw_tried") and not st.session_state.get("pw_ok"):
        st.error("비밀번호가 맞지 않아요. 다시 입력해 주세요.")
    return False


def main():
    st.set_page_config(page_title="나의 인생 여행지 찾기", page_icon="✈️", layout="centered")
    st.markdown(CSS, unsafe_allow_html=True)
    if not password_gate():
        return
    init_state()
    step = st.session_state.step
    if step == 0:
        page_intro()
    elif step <= len(QUESTIONS):
        page_question(step)
    else:
        page_result()


if __name__ == "__main__":
    main()
