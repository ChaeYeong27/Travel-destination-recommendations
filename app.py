        f'<div class="bp-head"><span>✈ BOARDING PASS</span><span class="rk">{rk}</span></div>'
        '<div class="bp-body">'
        '<div class="bp-route">'
        '<div><div class="k">FROM</div><div class="code">ICN</div><div class="nm">SEOUL · 인천</div></div>'
        f'<div class="mid">{BAND_LABEL[d["band"]]}<div class="path"><span>✈</span></div>SKY PICK AIR</div>'
        f'<div class="to"><div class="k">TO</div><div class="code">{code}</div><div class="nm">{d["name"]}</div></div>'
        '</div>'
        f'<div class="bp-grid">{grid}</div>'
