FLIGHT_LIMIT = {1: 0, 2: 1, 3: 2, 4: 3}   # Q3 보기 → 허용되는 최대 band


def score(d, a):
    q1, q2, q3, q4, q5, q6, q7, q8, q9, q10, q11, q12 = a
    s = 0.0
    sign = lambda opt: 1 if opt == 1 else -1

    # Q1 예산
    if q1 == 1:
        s -= 1.0 if d["cost"] == 2 else 0
    else:
        s += 0.8 * (d["cost"] - 1)

    # Q2 휴양/액티비티, Q4 도시/자연 (핵심 성향 → 가중치 큼)
    s += 2.0 * sign(q2) * d["rest"]
    s += 2.0 * sign(q4) * d["city"]

    # Q3 비행시간: 고른 구간과 정확히 같으면 가점 (가까운 곳만 계속 나오는 것 방지)
    if d["band"] == FLIGHT_LIMIT[q3]:
        s += 2.0

    # Q5 낯선 음식
    s += 0.5 * d["exotic"] if q5 == 1 else -1.5 * d["exotic"]

    # Q6 뚜벅이/자동차
    s += 1.0 * sign(q6) * d["walk"]

    # Q7 위생
    s += -1.5 * d["hyg"] if q7 == 1 else 0.3 * d["hyg"]

    # Q8 날씨
    s += 1.5 * sign(q8) * d["hot"]

    # Q9 쇼핑
    s += 1.0 * d["shop"] if q9 == 1 else -0.5 * d["shop"]

    # Q10 일정
    s += 1.0 * sign(q10) * d["packed"]

    # Q11 전통/현대
    s += 1.2 * sign(q11) * d["trad"]

    # Q12 여행기간: 짧으면 먼 곳 감점, 길면 먼 곳 가점
    s += -0.8 * d["band"] if q12 == 1 else 0.6 * d["band"]
    return s + BONUS.get(d["name"], 0)


def recommend(answers, top_n=3):
    """answers: 12개 보기 번호 리스트. 상위 top_n개 여행지 dict 리스트 반환"""
    q1, q3 = answers[0], answers[2]
    cands = [d for d in DESTINATIONS
             if d["band"] <= FLIGHT_LIMIT[q3] and not (q1 == 1 and d["cost"] == 3)]
    ranked = sorted(enumerate(cands), key=lambda x: (-score(x[1], answers), x[0]))
    return [d for _, d in ranked[:top_n]]

