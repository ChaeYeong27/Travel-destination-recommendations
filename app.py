def match_percent(d, a):
    """답변과 여행지 속성이 얼마나 맞는지 0~100으로 환산 (탑승권 표시용)"""
    side = lambda opt: 1 if opt == 1 else -1
    parts = []
    for key, qi in (("rest", 1), ("city", 3), ("walk", 5), ("hot", 7), ("packed", 9), ("trad", 10)):
        v = d[key] * side(a[qi])
        parts.append(1.0 if v > 0 else 0.6 if v == 0 else 0.2)
    parts.append(1.0 if a[4] == 1 else 1 - d["exotic"] / 2.5)
    parts.append(1 - d["hyg"] / 2.5 if a[6] == 1 else 1.0)
    parts.append(0.6 + d["shop"] / 5 if a[8] == 1 else 1 - d["shop"] / 4)
    parts.append(1.0 if d["band"] == FLIGHT_LIMIT[a[2]] else 0.75)
    parts.append(1 - d["band"] / 5 if a[11] == 1 else 0.6 + d["band"] / 7.5)
    return round(sum(parts) / len(parts) * 100)


